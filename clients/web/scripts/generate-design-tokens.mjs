import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import prettier from "prettier";

const DTCG_SCHEMA = "https://www.designtokens.org/schemas/2025.10/format.json";
const CSS_EXTENSION = "org.chimwemwe.css";
const PROFILE_ID_PATTERN = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;
const TOKEN_SEGMENT_PATTERN = /^[a-z0-9][a-z0-9-]*$/;
const ALIAS_PATTERN = /^\{([a-z0-9][a-z0-9.-]*)\}$/;
const EMBEDDED_ALIAS_PATTERN = /\{([a-z0-9][a-z0-9.-]*)\}/g;
const ALLOWED_TYPES = new Set([
  "color",
  "dimension",
  "duration",
  "fontFamily",
  "number",
  "shadow",
]);
const GENERATOR_HEADER =
  "/* Generated by scripts/generate-design-tokens.mjs. Do not edit. */";

function fail(message) {
  throw new Error(message);
}

function isRecord(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function assertRecord(value, label) {
  if (!isRecord(value)) fail(`${label} must be an object`);
}

function assertExactKeys(value, allowed, label) {
  const unexpected = Object.keys(value).filter((key) => !allowed.has(key));
  if (unexpected.length > 0) {
    fail(`${label} contains unsupported keys: ${unexpected.sort().join(", ")}`);
  }
}

function canonicalize(value) {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (!isRecord(value)) return value;

  return Object.fromEntries(
    Object.keys(value)
      .sort()
      .map((key) => [key, canonicalize(value[key])]),
  );
}

function tokenPathToCssName(tokenPath) {
  const name = `--${tokenPath.split(".").join("-")}`;
  if (!/^--[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) {
    fail(`token ${tokenPath} cannot produce a safe CSS custom-property name`);
  }
  return name;
}

function dimensionToCss(value, label) {
  assertRecord(value, label);
  assertExactKeys(value, new Set(["unit", "value"]), label);
  if (typeof value.value !== "number" || !Number.isFinite(value.value)) {
    fail(`${label}.value must be a finite number`);
  }
  if (!new Set(["px", "rem"]).has(value.unit)) {
    fail(`${label}.unit must be px or rem`);
  }
  return `${value.value}${value.unit}`;
}

function durationToCss(value, label) {
  assertRecord(value, label);
  assertExactKeys(value, new Set(["unit", "value"]), label);
  if (
    typeof value.value !== "number" ||
    value.value < 0 ||
    !Number.isFinite(value.value)
  ) {
    fail(`${label}.value must be a non-negative finite number`);
  }
  if (!new Set(["ms", "s"]).has(value.unit)) {
    fail(`${label}.unit must be ms or s`);
  }
  return `${value.value}${value.unit}`;
}

function validateColor(value, label) {
  assertRecord(value, label);
  assertExactKeys(value, new Set(["alpha", "colorSpace", "components", "hex"]), label);
  if (value.colorSpace !== "srgb") fail(`${label}.colorSpace must be srgb`);
  if (
    !Array.isArray(value.components) ||
    value.components.length !== 3 ||
    value.components.some(
      (component) =>
        typeof component !== "number" ||
        component < 0 ||
        component > 1 ||
        !Number.isFinite(component),
    )
  ) {
    fail(`${label}.components must contain three finite sRGB values from 0 to 1`);
  }
  if (
    value.alpha !== undefined &&
    (typeof value.alpha !== "number" || value.alpha < 0 || value.alpha > 1)
  ) {
    fail(`${label}.alpha must be a number from 0 to 1`);
  }
  if (value.hex !== undefined) {
    if (!/^#[0-9a-f]{6}(?:[0-9a-f]{2})?$/i.test(value.hex)) {
      fail(`${label}.hex must be a six- or eight-digit hexadecimal color`);
    }
    const componentHex = value.components
      .map((component) =>
        Math.round(component * 255)
          .toString(16)
          .padStart(2, "0"),
      )
      .join("");
    if (value.hex.slice(1, 7).toLowerCase() !== componentHex) {
      fail(`${label}.hex does not match its sRGB components`);
    }
  }
}

function colorToCss(value, label) {
  validateColor(value, label);
  if (value.hex) {
    const hex = value.hex.toLowerCase();
    const channels = hex.slice(1).match(/.{2}/g);
    if (channels.every((channel) => channel[0] === channel[1])) {
      return `#${channels.map((channel) => channel[0]).join("")}`;
    }
    return hex;
  }

  const channels = value.components.map((component) => Math.round(component * 255));
  const alpha = value.alpha ?? 1;
  return alpha === 1
    ? `rgb(${channels.join(" ")})`
    : `rgb(${channels.join(" ")} / ${Math.round(alpha * 10000) / 100}%)`;
}

function validateShadow(value, label) {
  const shadows = Array.isArray(value) ? value : [value];
  if (shadows.length === 0) fail(`${label} must contain at least one shadow`);

  for (const [index, shadow] of shadows.entries()) {
    const shadowLabel = `${label}[${index}]`;
    assertRecord(shadow, shadowLabel);
    assertExactKeys(
      shadow,
      new Set(["blur", "color", "offsetX", "offsetY", "spread"]),
      shadowLabel,
    );
    validateColor(shadow.color, `${shadowLabel}.color`);
    dimensionToCss(shadow.offsetX, `${shadowLabel}.offsetX`);
    dimensionToCss(shadow.offsetY, `${shadowLabel}.offsetY`);
    dimensionToCss(shadow.blur, `${shadowLabel}.blur`);
    dimensionToCss(shadow.spread, `${shadowLabel}.spread`);
  }
}

function shadowToCss(value, label) {
  validateShadow(value, label);
  const shadows = Array.isArray(value) ? value : [value];
  return shadows
    .map((shadow, index) => {
      const shadowLabel = `${label}[${index}]`;
      return [
        dimensionToCss(shadow.offsetX, `${shadowLabel}.offsetX`),
        dimensionToCss(shadow.offsetY, `${shadowLabel}.offsetY`),
        dimensionToCss(shadow.blur, `${shadowLabel}.blur`),
        dimensionToCss(shadow.spread, `${shadowLabel}.spread`),
        colorToCss(shadow.color, `${shadowLabel}.color`),
      ].join(" ");
    })
    .join(", ");
}

function validateFontFamily(value, label) {
  const families = Array.isArray(value) ? value : [value];
  if (
    families.length === 0 ||
    families.some(
      (family) =>
        typeof family !== "string" ||
        family.trim() === "" ||
        !/^-?[a-zA-Z][a-zA-Z0-9 -]*$/.test(family),
    )
  ) {
    fail(`${label} must contain only safe, non-empty font-family names`);
  }
}

function validateTypedValue(type, value, label) {
  if (typeof value === "string" && ALIAS_PATTERN.test(value)) return;

  switch (type) {
    case "color":
      validateColor(value, label);
      return;
    case "dimension":
      dimensionToCss(value, label);
      return;
    case "duration":
      durationToCss(value, label);
      return;
    case "fontFamily":
      validateFontFamily(value, label);
      return;
    case "number":
      if (typeof value !== "number" || !Number.isFinite(value)) {
        fail(`${label} must be a finite number`);
      }
      return;
    case "shadow":
      validateShadow(value, label);
      return;
    default:
      fail(`${label} uses unsupported token type ${type}`);
  }
}

function readCssExtension(extensions, label) {
  if (extensions === undefined) return null;
  assertRecord(extensions, `${label}.$extensions`);
  assertExactKeys(extensions, new Set([CSS_EXTENSION]), `${label}.$extensions`);

  const css = extensions[CSS_EXTENSION];
  assertRecord(css, `${label}.$extensions.${CSS_EXTENSION}`);
  assertExactKeys(css, new Set(["value"]), `${label}.$extensions.${CSS_EXTENSION}`);
  if (typeof css.value !== "string" || css.value.trim() === "") {
    fail(`${label} CSS extension value must be a non-empty string`);
  }
  const valueWithoutAliases = css.value.replace(EMBEDDED_ALIAS_PATTERN, "");
  if (
    /[;{}]/.test(valueWithoutAliases) ||
    /(?:url\s*\(|@import|expression\s*\(|var\s*\()/i.test(css.value)
  ) {
    fail(`${label} CSS extension contains a forbidden construct`);
  }
  return css.value;
}

function collectTokens(document, label) {
  assertRecord(document, label);
  if (document.$schema !== DTCG_SCHEMA) {
    fail(`${label} must declare the pinned DTCG 2025.10 schema`);
  }

  const tokens = new Map();

  function walk(node, segments, inheritedType) {
    assertRecord(node, `${label}:${segments.join(".") || "root"}`);
    const nodeLabel = `${label}:${segments.join(".") || "root"}`;
    const type = node.$type ?? inheritedType;

    if (Object.hasOwn(node, "$value")) {
      assertExactKeys(
        node,
        new Set(["$deprecated", "$description", "$extensions", "$type", "$value"]),
        nodeLabel,
      );
      if (segments.length === 0) fail(`${nodeLabel} cannot be a root token`);
      if (!ALLOWED_TYPES.has(type)) fail(`${nodeLabel} must declare a supported $type`);

      validateTypedValue(type, node.$value, `${nodeLabel}.$value`);
      const cssExtension = readCssExtension(node.$extensions, nodeLabel);
      const tokenPath = segments.join(".");
      tokens.set(tokenPath, {
        cssExtension,
        cssName: tokenPathToCssName(tokenPath),
        path: tokenPath,
        type,
        value: node.$value,
      });
      return;
    }

    const allowedMetadata = new Set([
      "$deprecated",
      "$description",
      "$extensions",
      "$schema",
      "$type",
    ]);
    for (const key of Object.keys(node)) {
      if (key.startsWith("$") && !allowedMetadata.has(key)) {
        fail(`${nodeLabel} contains unsupported metadata key ${key}`);
      }
    }
    if (node.$extensions !== undefined) {
      fail(`${nodeLabel} group extensions are not supported by the bounded generator`);
    }
    if (type !== undefined && !ALLOWED_TYPES.has(type)) {
      fail(`${nodeLabel} uses unsupported inherited token type ${type}`);
    }

    const childKeys = Object.keys(node)
      .filter((key) => !key.startsWith("$"))
      .sort();
    if (childKeys.length === 0) fail(`${nodeLabel} must contain at least one token`);

    for (const key of childKeys) {
      if (!TOKEN_SEGMENT_PATTERN.test(key)) {
        fail(`${nodeLabel} contains invalid token segment ${key}`);
      }
      walk(node[key], [...segments, key], type);
    }
  }

  walk(document, [], undefined);
  return tokens;
}

function dependenciesFor(token) {
  const dependencies = [];
  if (typeof token.value === "string") {
    const match = token.value.match(ALIAS_PATTERN);
    if (match) dependencies.push({ path: match[1], requireSameType: true });
  }
  if (token.cssExtension) {
    for (const match of token.cssExtension.matchAll(EMBEDDED_ALIAS_PATTERN)) {
      dependencies.push({ path: match[1], requireSameType: false });
    }
  }
  return dependencies;
}

function validateTokenGraph(tokens, label) {
  const cssNames = new Map();
  for (const token of tokens.values()) {
    const existing = cssNames.get(token.cssName);
    if (existing && existing !== token.path) {
      fail(`${label} tokens ${existing} and ${token.path} collide at ${token.cssName}`);
    }
    cssNames.set(token.cssName, token.path);

    for (const dependency of dependenciesFor(token)) {
      const target = tokens.get(dependency.path);
      if (!target)
        fail(
          `${label} token ${token.path} references unknown token ${dependency.path}`,
        );
      if (dependency.requireSameType && target.type !== token.type) {
        fail(
          `${label} token ${token.path} (${token.type}) cannot alias ${dependency.path} (${target.type})`,
        );
      }
    }
  }

  const visiting = new Set();
  const visited = new Set();

  function visit(tokenPath, chain) {
    if (visiting.has(tokenPath)) {
      fail(`${label} contains an alias cycle: ${[...chain, tokenPath].join(" -> ")}`);
    }
    if (visited.has(tokenPath)) return;

    visiting.add(tokenPath);
    const token = tokens.get(tokenPath);
    for (const dependency of dependenciesFor(token)) {
      visit(dependency.path, [...chain, tokenPath]);
    }
    visiting.delete(tokenPath);
    visited.add(tokenPath);
  }

  for (const tokenPath of tokens.keys()) visit(tokenPath, []);
}

function fontFamilyToCss(value) {
  const families = Array.isArray(value) ? value : [value];
  return families
    .map((family) => (/\s/.test(family) ? JSON.stringify(family) : family))
    .join(", ");
}

function replaceEmbeddedAliases(value, tokens, label) {
  return value.replace(EMBEDDED_ALIAS_PATTERN, (_match, targetPath) => {
    const target = tokens.get(targetPath);
    if (!target) fail(`${label} references unknown token ${targetPath}`);
    return `var(${target.cssName})`;
  });
}

function tokenToCss(token, tokens, label) {
  if (token.cssExtension) {
    return replaceEmbeddedAliases(token.cssExtension, tokens, label);
  }
  if (typeof token.value === "string") {
    const alias = token.value.match(ALIAS_PATTERN);
    if (alias) return `var(${tokens.get(alias[1]).cssName})`;
  }

  switch (token.type) {
    case "color":
      return colorToCss(token.value, label);
    case "dimension":
      return dimensionToCss(token.value, label);
    case "duration":
      return durationToCss(token.value, label);
    case "fontFamily":
      return fontFamilyToCss(token.value);
    case "number":
      return String(token.value);
    case "shadow":
      return shadowToCss(token.value, label);
    default:
      fail(`${label} uses unsupported token type ${token.type}`);
  }
}

function validateProfiles(document, profileDocuments) {
  assertRecord(document, "profiles.json");
  assertExactKeys(
    document,
    new Set(["defaultProfile", "profiles", "schemaVersion"]),
    "profiles.json",
  );
  if (document.schemaVersion !== 1) fail("profiles.json schemaVersion must be 1");
  if (!Array.isArray(document.profiles) || document.profiles.length === 0) {
    fail("profiles.json must declare at least one profile");
  }

  const seenIds = new Set();
  const profiles = document.profiles.map((profile, index) => {
    const label = `profiles.json profile ${index}`;
    assertRecord(profile, label);
    assertExactKeys(
      profile,
      new Set(["colorScheme", "description", "id", "label", "tokens"]),
      label,
    );
    if (typeof profile.id !== "string" || !PROFILE_ID_PATTERN.test(profile.id)) {
      fail(`${label}.id is invalid`);
    }
    if (seenIds.has(profile.id)) fail(`${label}.id duplicates ${profile.id}`);
    seenIds.add(profile.id);
    if (
      typeof profile.label !== "string" ||
      profile.label.trim() === "" ||
      profile.label.length > 80
    ) {
      fail(`${label}.label must be 1 to 80 characters`);
    }
    if (
      typeof profile.description !== "string" ||
      profile.description.trim() === "" ||
      profile.description.length > 180
    ) {
      fail(`${label}.description must be 1 to 180 characters`);
    }
    if (!new Set(["dark", "light"]).has(profile.colorScheme)) {
      fail(`${label}.colorScheme must be light or dark`);
    }
    if (typeof profile.tokens !== "string" || profile.tokens.trim() === "") {
      fail(`${label}.tokens must identify a token document`);
    }
    if (!profileDocuments.has(profile.id)) {
      fail(`${label} has no loaded token document`);
    }
    return profile;
  });

  if (!seenIds.has(document.defaultProfile)) {
    fail("profiles.json defaultProfile must identify a declared profile");
  }
  return profiles;
}

function mergeTokenMaps(referenceTokens, profileTokens, profileId) {
  const merged = new Map(referenceTokens);
  for (const [tokenPath, token] of profileTokens) {
    if (merged.has(tokenPath)) {
      fail(`profile ${profileId} token ${tokenPath} duplicates a reference token`);
    }
    merged.set(tokenPath, token);
  }
  return merged;
}

function validateProfileCompleteness(profiles, profileTokens) {
  const defaultProfile = profiles.find((profile) => profile.isDefault);
  const contract = profileTokens.get(defaultProfile.id);
  const requiredPaths = [...contract.keys()].sort();

  for (const profile of profiles) {
    const tokens = profileTokens.get(profile.id);
    const paths = [...tokens.keys()].sort();
    if (JSON.stringify(paths) !== JSON.stringify(requiredPaths)) {
      const missing = requiredPaths.filter((tokenPath) => !tokens.has(tokenPath));
      const extra = paths.filter((tokenPath) => !contract.has(tokenPath));
      fail(
        `profile ${profile.id} does not match the semantic token contract` +
          `${missing.length ? `; missing: ${missing.join(", ")}` : ""}` +
          `${extra.length ? `; extra: ${extra.join(", ")}` : ""}`,
      );
    }
    for (const tokenPath of requiredPaths) {
      if (tokens.get(tokenPath).type !== contract.get(tokenPath).type) {
        fail(`profile ${profile.id} changes the type of semantic token ${tokenPath}`);
      }
    }
  }
}

async function formatArtifact(source, parser) {
  return prettier.format(source, { parser, printWidth: 88 });
}

function renderDeclarations(tokens, allTokens) {
  return [...tokens.values()]
    .sort((left, right) => left.cssName.localeCompare(right.cssName))
    .map(
      (token) =>
        `    ${token.cssName}: ${tokenToCss(token, allTokens, `token ${token.path}`)};`,
    )
    .join("\n");
}

function renderProfilesTypeScript(profiles, defaultProfile, revision) {
  const profileRows = profiles
    .map(
      (profile) => `  {
    id: ${JSON.stringify(profile.id)},
    label: ${JSON.stringify(profile.label)},
    description: ${JSON.stringify(profile.description)},
    colorScheme: ${JSON.stringify(profile.colorScheme)},
  },`,
    )
    .join("\n");

  return `${GENERATOR_HEADER}

export const designTokenRevision =
  ${JSON.stringify(revision)} as const;

export const defaultExperienceProfileId = ${JSON.stringify(defaultProfile)} as const;

export const experienceProfiles = [
${profileRows}
] as const;

export type ExperienceProfileId = (typeof experienceProfiles)[number]["id"];
`;
}

export async function compileDesignTokenDocuments({
  profileDocuments,
  profilesDocument,
  referenceDocument,
}) {
  if (!(profileDocuments instanceof Map))
    fail("profileDocuments must be a Map keyed by profile ID");

  const referenceTokens = collectTokens(referenceDocument, "reference.tokens.json");
  const declaredProfiles = validateProfiles(profilesDocument, profileDocuments);
  const profiles = declaredProfiles
    .map((profile) => ({
      ...profile,
      isDefault: profile.id === profilesDocument.defaultProfile,
    }))
    .sort(
      (left, right) =>
        Number(right.isDefault) - Number(left.isDefault) ||
        left.id.localeCompare(right.id),
    );

  const profileTokens = new Map();
  const combinedTokens = new Map();
  for (const profile of profiles) {
    const tokens = collectTokens(profileDocuments.get(profile.id), profile.tokens);
    const merged = mergeTokenMaps(referenceTokens, tokens, profile.id);
    validateTokenGraph(merged, `profile ${profile.id}`);
    profileTokens.set(profile.id, tokens);
    combinedTokens.set(profile.id, merged);
  }
  validateProfileCompleteness(profiles, profileTokens);

  const revisionInput = {
    profileDocuments: Object.fromEntries(
      [...profileDocuments.entries()].sort(([left], [right]) =>
        left.localeCompare(right),
      ),
    ),
    profilesDocument,
    referenceDocument,
  };
  const revision = `sha256:${crypto
    .createHash("sha256")
    .update(JSON.stringify(canonicalize(revisionInput)))
    .digest("hex")}`;

  const referenceCss = `${GENERATOR_HEADER}
@layer tokens {
  :root {
${renderDeclarations(referenceTokens, referenceTokens)}
  }
}
`;

  const profileBlocks = profiles
    .map((profile) => {
      const selectors = profile.isDefault
        ? `:root,\n  :root[data-theme=${JSON.stringify(profile.id)}]`
        : `:root[data-theme=${JSON.stringify(profile.id)}]`;
      return `  ${selectors} {
    color-scheme: ${profile.colorScheme};

${renderDeclarations(profileTokens.get(profile.id), combinedTokens.get(profile.id))}
  }`;
    })
    .join("\n\n");

  const themesCss = `${GENERATOR_HEADER}
@layer themes {
${profileBlocks}
}
`;

  return {
    artifacts: new Map([
      ["tokens.css", await formatArtifact(referenceCss, "css")],
      ["themes.css", await formatArtifact(themesCss, "css")],
      [
        "profiles.ts",
        await formatArtifact(
          renderProfilesTypeScript(profiles, profilesDocument.defaultProfile, revision),
          "typescript",
        ),
      ],
    ]),
    profileCount: profiles.length,
    referenceTokenCount: referenceTokens.size,
    revision,
    semanticTokenCount: profileTokens.get(profilesDocument.defaultProfile).size,
  };
}

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (error) {
    fail(`${path.relative(process.cwd(), file)} is not valid JSON: ${error.message}`);
  }
}

function resolveProfileTokenFile(tokensRoot, relativeFile) {
  const resolved = path.resolve(tokensRoot, relativeFile);
  const relative = path.relative(tokensRoot, resolved);
  if (relative.startsWith("..") || path.isAbsolute(relative)) {
    fail(`profile token file escapes the token source directory: ${relativeFile}`);
  }
  return resolved;
}

export async function loadAndCompileDesignTokens(projectRoot) {
  const tokensRoot = path.join(projectRoot, "src", "design-system", "tokens");
  const profilesDocument = readJson(path.join(tokensRoot, "profiles.json"));
  const referenceDocument = readJson(path.join(tokensRoot, "reference.tokens.json"));
  const profileDocuments = new Map();

  if (Array.isArray(profilesDocument.profiles)) {
    for (const profile of profilesDocument.profiles) {
      if (
        isRecord(profile) &&
        typeof profile.id === "string" &&
        typeof profile.tokens === "string"
      ) {
        profileDocuments.set(
          profile.id,
          readJson(resolveProfileTokenFile(tokensRoot, profile.tokens)),
        );
      }
    }
  }

  return compileDesignTokenDocuments({
    profileDocuments,
    profilesDocument,
    referenceDocument,
  });
}

async function main() {
  const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const outputRoot = path.join(projectRoot, "src", "design-system", "generated");
  const checkOnly = process.argv.slice(2).includes("--check");
  const unexpectedArguments = process.argv
    .slice(2)
    .filter((argument) => argument !== "--check");
  if (unexpectedArguments.length > 0) {
    fail(`unsupported arguments: ${unexpectedArguments.join(", ")}`);
  }

  const result = await loadAndCompileDesignTokens(projectRoot);
  const stale = [];

  for (const [name, content] of result.artifacts) {
    const file = path.join(outputRoot, name);
    if (checkOnly) {
      if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content)
        stale.push(name);
    } else {
      fs.mkdirSync(outputRoot, { recursive: true });
      fs.writeFileSync(file, content);
    }
  }

  if (stale.length > 0) {
    fail(
      `generated design-token output is stale: ${stale.join(", ")}; run npm run generate:design-tokens`,
    );
  }

  const action = checkOnly ? "current" : "generated";
  console.log(
    `Design token artifacts ${action} (${result.referenceTokenCount} reference tokens, ` +
      `${result.semanticTokenCount} semantic tokens, ${result.profileCount} ` +
      `profile${result.profileCount === 1 ? "" : "s"}, ` +
      `${result.revision}).`,
  );
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : null;
if (invokedPath === fileURLToPath(import.meta.url)) {
  try {
    await main();
  } catch (error) {
    console.error(`Design token generation failed: ${error.message}`);
    process.exitCode = 1;
  }
}
